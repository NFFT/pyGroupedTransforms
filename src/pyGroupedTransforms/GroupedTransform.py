def get_superposition_set(d, ds):
    r"""Return the superposition set of order ``ds`` in ``d`` dimensions.

    That is

    .. math::

        U^{(d,ds)} = \{ \pmb u \subset \{1,2,\dots,d\} : |\pmb u| \leq ds \}.

    Args:
        d (int): Number of dimensions.
        ds (int): Maximum interaction order.

    Returns:
        list[tuple[int]]: All subsets of ``{0, ..., d-1}`` of size at most
        ``ds``, starting with the empty tuple.
    """
    nset = [[j] for j in range(d)]
    returnset = [[]] + nset
    for i in range(ds - 1):
        nextnset = []
        for s in nset:
            for j in range(d):
                if s[-1] < j:
                    nextnset.append(s + [j])
        returnset = returnset + nextnset
        nset = nextnset

    return [tuple(item) for item in returnset]


def get_setting(
    system, N, U=None, d=None, ds=None
):  # I have to add bases and NFMT stuff here!
    r"""Build the :py:class:`Setting` list describing an ANOVA index set.

    The index set can be given either explicitly through ``U``, or implicitly
    through ``d`` and ``ds``, in which case it is generated by
    :py:func:`get_superposition_set`. Passing ``d`` takes precedence.

    Args:
        system (str): One of ``"exp"``, ``"cos"``, ``"chui1"`` … ``"chui4"``
            or ``"mixed"``.
        N (list[int]): Bandwidths. With ``d``/``ds`` there must be exactly
            ``ds`` entries, one per interaction order.
        U (list[tuple[int]], optional): Explicit index set.
        d (int, optional): Number of dimensions, used with ``ds``.
        ds (int, optional): Maximum interaction order, used with ``d``.

    Returns:
        list[Setting]: One setting per ANOVA term.

    Raises:
        ValueError: If ``system`` is unknown, or if ``N`` does not have ``ds``
            entries when ``d`` is given.
    """
    if system not in systems:
        raise ValueError("System not found.")

    if d != None:  # Input system::String, d::Int,  ds::Int, N::Vector{Int}

        if len(N) != ds:
            raise ValueError("N must have ds entries.")

        tmp = np.concatenate(([0], N))
        U = get_superposition_set(d, ds)
        bwl = [np.full(len(u), tmp[len(u)], "int32") for u in U]

        if systems[system] == NFMTtools:
            if len(basis_vect) == 0:
                ValueError(
                    "please call get_setting with basis_vect for a NFMT transform."
                )
            if len(basis_vect) < d:
                ValueError("basis_vect must have an entry for every dimension.")
            return [
                Setting(
                    u=U[idx],
                    mode=systems[system],
                    bandwidths=np.array(bwl[idx], "int32"),
                    bases=basis_vect[U[idk]],
                )
                for idx in range(len(U))
            ]

        else:
            return [
                Setting(
                    u=U[idx],
                    mode=systems[system],
                    bandwidths=np.array(bwl[idx], "int32"),
                )
                for idx in range(len(U))
            ]

    if len(N) != len(U):
        raise ValueError("N must have |U| entries.")

    if type(N[0]) == int:  # Input system::String,  U::list{list{Int}},  N::list{Int}

        bwl = [None] * len(U)

        for i, u in enumerate(U):
            if len(u) == 0:
                bwl[i] = [0] * len(u)
            else:
                bwl[i] = np.full(len(u), N[i])

        if systems[system] == NFMTtools:
            if len(basis_vect) == 0:
                ValueError(
                    "please call get_setting with basis_vect for a NFMT transform."
                )
            if len(basis_vect) < max(max(u) for u in U):
                ValueError("basis_vect must have an entry for every dimension.")
            return [
                Setting(
                    u=u,
                    mode=systems[system],
                    bandwidths=np.array(bwl[i], "int32"),
                    bases=basis_vect[u],
                )
                for i, u in enumerate(U)
            ]

        else:
            return [
                Setting(u=u, mode=systems[system], bandwidths=np.array(bwl[i], "int32"))
                for i, u in enumerate(U)
            ]

    elif (
        type(N[0]) == list or type(N[0]) == np.ndarray
    ):  # Input system::String,  U::list{list{Int}},  N::list{list{Int}} oder list{np.ndarray}

        bwl = [None] * len(U)

        for i, u in enumerate(U):
            if len(u) == 0:
                bwl[i] = [0] * len(u)
            else:
                if len(N[i]) != len(u):
                    raise ValueError(
                        "Vector N has for the set", u, "not the right length"
                    )
                bwl[i] = N[i]

        if systems[system] == NFMTtools:
            if len(basis_vect) == 0:
                ValueError(
                    "please call get_setting with basis_vect for a NFMT transform."
                )
            if len(basis_vect) < max(max(u) for u in U):
                ValueError("basis_vect must have an entry for every dimension.")
            return [
                Setting(
                    u=U[idx],
                    mode=systems[system],
                    bandwidths=np.array(bwl[idx], "int32"),
                    bases=basis_vect[U[idk]],
                )
                for idx in range(len(U))
            ]

        else:
            return [
                Setting(
                    u=U[idx],
                    mode=systems[system],
                    bandwidths=np.array(bwl[idx], "int32"),
                )
                for idx in range(len(U))
            ]


class GroupedTransform:
    r"""A grouped transformation over an ANOVA index set.

    Bundles the low-dimensional sub-transforms belonging to each ANOVA term
    into one operator. The settings can be supplied in three ways:

    - directly, as a list of :py:class:`Setting` objects via ``settings``
    - by index set, passing ``U`` and ``N``
    - by dimension and order, passing ``d``, ``ds`` and ``N``

    Args:
        system (str): Which family of sub-transforms to use. One of ``"exp"``
            (exponentials, NFFT), ``"cos"`` (cosine, NFCT), ``"chui1"`` …
            ``"chui4"`` (Chui-Wang wavelets), or ``"mixed"`` (per-dimension,
            see ``basis_vect``).
        X (numpy.ndarray): Nodes, ``M`` rows and ``d`` columns. Must lie in
            ``[-0.5, 0.5)`` for ``"exp"`` and the ``"chui*"`` systems, and in
            ``[0, 0.5]`` for ``"cos"``.
        settings (list[Setting]): Pre-built settings. If empty, they are
            derived from ``U``/``N`` or ``d``/``ds``/``N``.
        algorithm (str, optional): Defaults to ``"nfft"``. ``"nfft"`` for the fast transforms, ``"keops"`` for implicit matrix multiplication (allow GPU or CPU computation),
            or ``"direct"`` to build the matrix explicitly. 
        device: Device used by the ``"keops"`` algorithm, allows user to manually switch between GPU or CPU computation. Supported values are: ``"cuda"`` 
            for NVIDIA and CUDA-supporting devices, ``"mps"`` for Apple MPS-supporting devices, ``"cpu"`` for selecting CPU processing.
            If ``None`` (default), the algorithm automatically selects the device based on availability, prioritizing GPU use.
        parallel (bool): Run the sub-transforms threaded. Defaults to ``True``.
        basis_vect (list[str]): Per-dimension basis, required for
            ``system="mixed"``; must have one entry per dimension.
        N (list): Bandwidths, one entry per ANOVA term or per interaction
            order.
        U (list[tuple[int]], optional): Index set defining the ANOVA terms.
        d (int, optional): Number of dimensions, used with ``ds``.
        ds (int, optional): Maximum interaction order, used with ``d``.

    Attributes:
        system (str): The chosen family of sub-transforms.
        settings (list[Setting]): One entry per ANOVA term, describing its
            dimensions, mode and bandwidths.
        X (numpy.ndarray): The nodes.
        transforms (list): The low-dimensional sub-transformations.
        basis_vect (list[str]): Per-dimension basis choice.
        algorithm (str): ``"nfft"`` or ``"direct"``.
        parallel (bool): Whether sub-transforms run threaded.

    Raises:
        ValueError: If ``system`` is unknown, or if the nodes in ``X`` lie
            outside the range the system requires.
    """

    def __init__(
        self,
        system,
        X,
        settings=[],
        algorithm="nfft",
        device=None,
        parallel=True,
        basis_vect=[],
        N=[],
        U=None,
        d=None,
        ds=None,
    ):

        if system not in systems:
            raise ValueError("System not found.")

        if system == "mixed":
            if len(basis_vect) == 0:
                ValueError(
                    "please call GroupedTransform with basis_vect for a NFMT transform."
                )
            if len(basis_vect) != X.shape[1]:
                ValueError("basis_vect must have an entry for every dimension.")

        if system in {"exp", "chui1", "chui2", "chui3", "chui4"}:
            if np.min(X) < -0.5 or np.max(X) >= 0.5:
                raise ValueError("Nodes must be between -0.5 and 0.5.")
        elif system == "cos":
            if np.min(X) < 0 or np.max(X) > 0.5:
                raise ValueError("Nodes must be between 0 and 0.5.")
        elif system == "mixed":
            basis_vals = np.array([NFMTtools.BASES[b] for b in basis_vect])

            cosine_mask = basis_vals > 0
            if np.sum(cosine_mask) > 0:
                if (np.min(X[cosine_mask, :]) < 0) or (np.max(X[cosine_mask, :]) > 1):
                    raise ValueError(
                        "Nodes must be between 0 and 1 for cosine or Chebyshev dimensions."
                    )

            exp_mask = ~cosine_mask
            if np.sum(exp_mask) > 0:
                if (np.min(X[exp_mask, :]) < -0.5) or (np.max(X[exp_mask, :]) > 0.5):
                    raise ValueError(
                        "Nodes must be between -0.5 and 0.5 for exponentional dimensions."
                    )

        if system in {"chui1", "chui2", "chui3", "chui4"}:
            algorithm = "nfft"

        self.algorithm = algorithm
        self.device = device
        self.basis_vect = basis_vect
        self.system = system
        self.X = X
        self.parallel = parallel

        if len(settings) == 0:
            self.settings = get_setting(system=system, N=N, U=U, d=d, ds=ds)
        else:
            self.settings = settings

        if algorithm == "nfft":
            self.matrix = np.empty((0, 0), dtype=object)
            self.transforms = [
                DeferredLinearOperator() for i in range(len(self.settings))
            ]
            for idx, s in enumerate(self.settings):
                if len(s.bandwidths) == 0:
                    u = (0,)
                else:
                    u = s.u
                if system.startswith("chui"):
                    Order = int(system[-1])
                    self.transforms[idx] = s.mode.get_transform(
                        bandwidths=s.bandwidths, X=np.copy(X[:, u], order="C"), m=Order
                    )
                elif system == "mixed":
                    self.transforms[idx] = s.mode.get_transform(
                        bandwidths=s.bandwidths,
                        X=np.copy(X[:, u], order="C"),
                        bases=s.bases,
                    )
                else:
                    self.transforms[idx] = s.mode.get_transform(
                        bandwidths=s.bandwidths, X=np.copy(X[:, u], order="C")
                    )
        elif algorithm == "keops":
            self.matrix = np.empty((0,0), dtype=object)
            
            if self.device:
                device = device
            else:    
                if torch.cuda.is_available():
                    device = "cuda"
                elif torch.mps.is_available():
                    device = "mps"
                else:
                    device = "cpu"
                    
            self.transforms = [
                DeferredLinearOperator()
                for _ in range(len(self.settings))
            ]
            
            D = X.shape[1]

            freq_list = []

            for s in self.settings:

                if len(s.bandwidths) == 0:
                    full = np.zeros((1, D), dtype=np.int32)
                    
                
                local = np.atleast_2d(
                    s.mode.index_set_without_zeros(
                        np.array(s.bandwidths, dtype=np.int32)
                    )
                ).T

                full = np.zeros((local.shape[0], D), dtype=np.int32)

                for i, dim in enumerate(s.u):
                    full[:, dim] = local[:, i]

                freq_list.append(full)

            freq = np.vstack(freq_list)
            
            X_torch = torch.tensor(X, dtype=torch.float64, device=device)
            I_torch = torch.tensor(
                freq,
                dtype=torch.float64,
                device=device
            )

            def trafo(fhat):
                if self.system == "cos" or self.system == "cheb":
                    mult = np.sqrt(2.0) ** np.count_nonzero(freq, axis=1)
                    mult_torch = torch.tensor(mult, dtype=torch.float64, device=device)

                    kernel = 1.0
                    for i in range(D):
                        Xi = LazyTensor(X_torch[:, None, i:i+1].contiguous())
                        Ki = LazyTensor(I_torch[None, :, i:i+1].contiguous())
                        kernel = kernel * (2 * torch.pi * Xi * Ki).cos()

                    fhat_torch = (
                        torch.as_tensor(fhat, dtype=torch.float64, device=device)
                        * mult_torch
                    )
                    fhat_j = LazyTensor(fhat_torch[None, :, None].contiguous())

                    try:
                        result = (kernel * fhat_j).sum(dim=1)
                        torch.cuda.synchronize()
                        return result.squeeze().cpu().numpy()
                    except Exception as e:
                        print("Error in KeOps trafo:", e)
                        return None
                else:
                    X_i = LazyTensor(X_torch[:, None, :].contiguous())
                    K_j = LazyTensor(I_torch[None, :, :].contiguous())

                    phase_fwd = (X_i * K_j).sum(-1)
                    two_pi_phase = -2 * torch.pi * phase_fwd
                    kernel = two_pi_phase.cos() + 1j * two_pi_phase.sin()

                    fhat_torch = torch.tensor(fhat, dtype=torch.complex128, device=device)
                    fhat_j = LazyTensor(fhat_torch[None, :, None].contiguous())

                    try:
                        result = (kernel * fhat_j).sum(dim=1)
                        torch.cuda.synchronize()
                        result = result.squeeze().cpu().numpy()
                        return result
                    except Exception as e:
                        print("Error in KeOps trafo:", e)
                        return None

            def adjoint(f):
                if self.system == "cos" or self.system == "cheb":
                    mult = np.sqrt(2.0) ** np.count_nonzero(freq, axis=1)
                    
                    f_torch = torch.as_tensor(
                        f, dtype=torch.float64, device=device
                    ).contiguous()

                    kernel = 1.0
                    for i in range(D):
                        Ki = LazyTensor(I_torch[:, None, i:i+1].contiguous())
                        Xi = LazyTensor(X_torch[None, :, i:i+1].contiguous())
                        kernel = kernel * (2 * torch.pi * Xi * Ki).cos()

                    f_i = LazyTensor(f_torch[None, :, None].contiguous())

                    try:
                        result = (kernel * f_i).sum(dim=1)
                        torch.cuda.synchronize()
                        result = result.squeeze().cpu().numpy()
                        return result * mult
                    except Exception as e:
                        print("Error in KeOps adjoint:", e)
                        return None
                else:
                    f_torch = torch.tensor(f, dtype=torch.complex128, device=device).contiguous()

                    X_i = LazyTensor(X_torch[None, :, :].contiguous())
                    K_j = LazyTensor(I_torch[:, None, :].contiguous())

                    phase = (K_j * X_i).sum(-1)
                    two_pi_phase = 2 * torch.pi * phase
                    kernel = two_pi_phase.cos() + 1j * two_pi_phase.sin()

                    f_i = LazyTensor(f_torch[None, :, None].contiguous())

                    try:
                        result = (kernel * f_i).sum(dim=1)
                        torch.cuda.synchronize()
                        result = result.squeeze().cpu().numpy()

                        return result
                    except Exception as e:
                        print("Error in KeOps adjoint:", e)
                        return None

            keops_dtype = np.float64 if self.system == "cos" else np.complex128
            self.transforms = [DeferredLinearOperator(
                dtype=keops_dtype, shape=(X.shape[0], len(freq)), mfunc=trafo, rmfunc=adjoint
            )]
    
        else:
            self.transforms = []
            s1 = self.settings[0]
            if len(s1.bandwidths) == 0:
                u1 = (0,)
            else:
                u1 = s1.u
            if system.startswith("chui"):
                raise ValueError(
                    "Direct computation with full matrix not supported for wavelet basis."
                )
            elif system == "mixed":
                matrix = np.array(
                    s1.mode.get_matrix(bandwidths=s1.bandwidths, X=X[:, u1].T),
                    bases=s1.bases,
                )
                for s in self.settings[1:]:
                    if len(s.bandwidths) == 0:
                        u = (0,)
                    else:
                        u = s.u
                    matrix = np.hstack(
                        [
                            matrix,
                            np.array(
                                s.mode.get_matrix(s.bandwidths, X[:, u].T),
                                bases=s.bases,
                            ),
                        ]
                    )
            else:
                matrix = np.array(
                    s1.mode.get_matrix(bandwidths=s1.bandwidths, X=X[:, u1].T)
                )
                for s in self.settings[1:]:
                    if len(s.bandwidths) == 0:
                        u = (0,)
                    else:
                        u = s.u
                    matrix = np.hstack(
                        [matrix, np.array(s.mode.get_matrix(s.bandwidths, X[:, u].T))]
                    )
            self.matrix = matrix

    def __mul__(self, other):
        r"""Apply the transform, or its adjoint, with the ``*`` operator.

        The direction is chosen from the type of ``other``:

        - a :py:class:`GroupedCoefficients` object evaluates the function,
          ``f = F * fhat``
        - a :py:class:`numpy.ndarray` of samples applies the adjoint,
          ``fhat = F * f``

        Args:
            other (GC or numpy.ndarray): Coefficients to evaluate, or samples
                to transform back.

        Returns:
            numpy.ndarray or GC: Function values for coefficient input,
            grouped coefficients for sample input.
        """
        if isinstance(other, np.ndarray):  # `f = F*f`    (f = other)
            if self.algorithm == "nfft":
                fhat = GroupedCoefficients(self.settings)

                def adjoint_worker(i):
                    adjoint_result = self.transforms[i].H @ other
                    fhat[self.settings[i].u] = adjoint_result

                if self.parallel:
                    threads = []
                    for i in range(len(self.transforms)):
                        t = threading.Thread(target=adjoint_worker, args=(i,))
                        t.start()
                        threads.append(t)

                    for t in threads:
                        t.join()

                else:
                    for i in range(len(self.transforms)):
                        adjoint_worker(i)

                return fhat
            
            elif self.algorithm == "keops":
                return GroupedCoefficients(self.settings, self.transforms[0].H @ other)  
             
            elif self.algorithm == "direct":
                return GroupedCoefficients(
                    self.settings, (self.matrix.conj()).T @ other
                )
                
        elif isinstance(other, GC):  # `f = F*fhat`    (fhat = other)
            if self.settings != other.settings:
                raise ValueError(
                    "The GroupedTransform and the GroupedCoefficients have different settings"
                )

            if self.algorithm == "nfft":
                results = []

                def worker(i):
                    u = self.settings[i].u
                    result = self.transforms[i] @ other[u]
                    results.append(result)

                if self.parallel:
                    threads = []
                    for i in range(len(self.transforms)):
                        t = threading.Thread(target=worker, args=(i,))
                        t.start()
                        threads.append(t)
                    for t in threads:
                        t.join()
                else:
                    for i in range(len(self.transforms)):
                        worker(i)

                return sum(results)
            
            elif self.algorithm == "keops":
                return self.transforms[0] @ other.data
            
            elif self.algorithm == "direct":
                return self.matrix @ other.data
        else:
            raise ValueError("Wrong input data type")

    def __matmul__(self, other):
        return self.__mul__(other)

    def adjoint(self):
        r"""Return the transform itself, for symmetry with the ``F'`` notation.

        :py:meth:`__mul__` decides from its argument whether to apply the
        forward or the adjoint transform, so no separate adjoint object is
        needed. This exists purely for convenience.

        Returns:
            GroupedTransform: ``self``.
        """
        return self

    @property
    def H(self):
        r"""Alias for :py:meth:`adjoint`, so ``F.H`` reads like the usual notation.

        Returns:
            GroupedTransform: ``self``.
        """
        return self

    def __getitem__(self, u):
        r"""Return the sub-transform belonging to one ANOVA term.

        Lets you write ``F[(1, 3)]`` to obtain the transform of the ANOVA term
        defined by ``u``.

        Args:
            u (tuple[int]): The coordinate subset identifying the term.

        Returns:
            The sub-transform for ``u`` — a linear operator for the ``"nfft"``
            algorithm, otherwise the corresponding matrix block.

        Raises:
            ValueError: If ``u`` is not one of the terms in this transform.
        """
        idx = next(
            (i for i, s in enumerate(self.settings) if len(s.u) == len(u) and s.u == u),
            None,
        )

        if idx is None:
            raise ValueError("This term is not contained")
        elif self.algorithm == "nfft":
            return self.transforms[idx]
        else:
            return self.get_matrix()

    def get_matrix(self):
        r"""Assemble and return the transformation as an explicit matrix.

        Returns:
            numpy.ndarray: The full transformation matrix.

        Raises:
            ValueError: For the wavelet systems ``"chui1"`` … ``"chui4"``,
                which have no direct matrix representation.
        """
        if self.system in ["chui1", "chui2", "chui3", "chui4"]:
            raise ValueError(
                "Direct computation with full matrix not supported for wavelet basis."
            )
        elif self.system == "mixed":
            s1 = self.settings[0]
            if len(s1.bandwidths) == 0:
                u1 = (0,)
            else:
                u1 = s1.u
            F_direct = s1.mode.get_matrix(s.bdanwidths, self.X[:, u1].T, bases=s.bases)
            for idx, s in enumerate(self.settings):
                if idx == 0:
                    continue
                if len(s.bandwidths) == 0:
                    u = (0,)
                else:
                    u = s.u
                mat = s.mode.get_matrix(s.bandwidths, self.X[:, u].T, s.bases)
                F_direct = np.hstack([F_direct, mat])
        else:
            s1 = self.settings[0]
            if len(s1.bandwidths) == 0:
                u1 = (0,)
            else:
                u1 = s1.u
            F_direct = s1.mode.get_matrix(s1.bandwidths, self.X[:, u1].T)

            for idx, s in enumerate(self.settings):
                if idx == 0:
                    continue
                if len(s.bandwidths) == 0:
                    u = (0,)
                else:
                    u = s.u
                mat = s.mode.get_matrix(s.bandwidths, self.X[:, u].T)
                F_direct = np.hstack((F_direct, mat))

            return F_direct
