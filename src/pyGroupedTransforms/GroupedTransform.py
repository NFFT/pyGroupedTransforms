"""Grouped transformations for ANOVA-style index sets.

The central object is :py:class:`GroupedTransform`, which bundles the
low-dimensional sub-transforms belonging to each ANOVA term into a single
operator. Applying it to a :py:class:`GroupedCoefficients` object evaluates the
function; applying it to a vector of samples computes the adjoint.

:py:func:`get_superposition_set` builds the index set for a given dimension and
interaction order, and :py:func:`get_setting` turns an index set and bandwidths
into the :py:class:`Setting` list a transform needs.
"""

